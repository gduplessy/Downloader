export type TransferLabel = keyof typeof rows;
export const transferLocales = ['en', 'fr', 'es', 'de', 'ar', 'zh-CN'] as const;
export function transferLabels(locale: string): Record<TransferLabel, string> {
  const language = locale.startsWith('zh') ? 'zh-CN' : locale.split('-')[0];
  const index = Math.max(0, transferLocales.indexOf(language as (typeof transferLocales)[number]));
  return Object.fromEntries(
    Object.entries(rows).map(([key, values]) => [key, values[index]]),
  ) as Record<TransferLabel, string>;
}
