export type Key = keyof typeof en;
export type Locale = 'en' | 'fr' | 'es' | 'de' | 'ar' | 'zh-CN';
export const languages: Record<Locale, string> = {
  en: 'English',
  fr: 'Français',
  es: 'Español',
  de: 'Deutsch',
  ar: 'العربية',
  'zh-CN': '简体中文',
};
export const dictionaries: Record<Locale, Record<Key, string>> = {
  en,
  fr: { ...en },
  es: { ...en },
  de: { ...en },
  ar: { ...en },
  'zh-CN': { ...en },
};
for (const [key, row] of Object.entries(translations)) {
  (['fr', 'es', 'de', 'ar', 'zh-CN'] as const).forEach((locale, index) => {
    dictionaries[locale][key as Key] = row[index];
  });
}
export function translate(locale: string, key: Key): string {
  return (dictionaries[locale as Locale] ?? en)[key] ?? en[key];
}
